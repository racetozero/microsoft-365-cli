//! Shell completion setup (omelette) and the clink Lua parser.

use m365_core::json::Obj;
use m365_core::{Result, Value};

pub const PWSH_SCRIPT: &str = include_str!("../assets/Register-CLIM365Completion.ps1");

/// The shell script omelette writes for `m365`; it asks `m365 --compgen`
/// for replies.
pub fn shell_script() -> String {
    r#"### m365 completion - begin. generated by omelette.js ###
if type compdef &>/dev/null; then
  _m365_completion() {
    compadd -- `m365 --compzsh --compgen "${CURRENT}" "${words[CURRENT-1]}" "${BUFFER}"`
  }
  compdef _m365_completion m365
  compdef _m365_completion microsoft365
elif type complete &>/dev/null; then
  _m365_completion() {
    local cur prev nb_colon
    _get_comp_words_by_ref -n : cur prev
    nb_colon=$(grep -o ":" <<< "$COMP_LINE" | wc -l)
    COMPREPLY=( $(compgen -W '$(m365 --compbash --compgen "$((COMP_CWORD - (nb_colon * 2)))" "$prev" "${COMP_LINE}")' -- "$cur") )
    __ltrim_colon_completions "$cur"
  }
  complete -F _m365_completion m365
  complete -F _m365_completion microsoft365
fi
### m365 completion - end ###
"#
    .to_string()
}

/// `omelette.setupShellInitFile()`: adds the loader to the shell's init file.
pub fn setup_shell_init_file() -> Result<()> {
    let home = m365_core::config::home();
    let shell = std::env::var("SHELL").unwrap_or_default();
    let (file, snippet) = if shell.contains("zsh") {
        (
            home.join(".zshrc"),
            "\n# begin m365 completion\n. <(m365 --completion)\n# end m365 completion\n"
                .to_string(),
        )
    } else if shell.contains("fish") {
        (
            home.join(".config/fish/config.fish"),
            "\n# begin m365 completion\nm365 --completion-fish | source\n# end m365 completion\n"
                .to_string(),
        )
    } else {
        (
            home.join(".bashrc"),
            "\n# begin m365 completion\n. <(m365 --completion)\n# end m365 completion\n"
                .to_string(),
        )
    };
    let existing = std::fs::read_to_string(&file).unwrap_or_default();
    if !existing.contains("# begin m365 completion") {
        if let Some(d) = file.parent() {
            std::fs::create_dir_all(d)?;
        }
        use std::io::Write;
        let mut f = std::fs::OpenOptions::new()
            .create(true)
            .append(true)
            .open(&file)?;
        f.write_all(snippet.as_bytes())?;
    }
    Ok(())
}

fn lua_name(s: &str) -> String {
    s.replace('-', "_")
}

fn build_branch(branch: &Value, functions: &mut Obj, name: &str) {
    if let Value::Object(o) = branch {
        for (k, v) in o {
            if v.as_object().is_some_and(|x| !x.is_empty())
                || v.as_array().is_some_and(|x| !x.is_empty())
            {
                build_branch(v, functions, &lua_name(&format!("{name}_{k}")));
            }
        }
    }
    let mut parser = vec!["parser({".to_string()];
    let mut printing_args = false;
    match branch {
        Value::Array(a) => {
            let mut items: Vec<String> = a.iter().map(m365_core::json::to_js_string).collect();
            items.sort();
            let n = items.len();
            for (i, c) in items.iter().enumerate() {
                parser.push(format!("\"{c}\"{}", if i < n - 1 { "," } else { "" }));
            }
        }
        Value::Object(o) => {
            let mut keys: Vec<&String> = o.keys().collect();
            keys.sort();
            let non_empty = |k: &str| {
                o[k].as_object().is_some_and(|x| !x.is_empty())
                    || o[k].as_array().is_some_and(|x| !x.is_empty())
            };
            if keys.iter().any(|k| k.starts_with('-')) {
                printing_args = true;
                let tmp: Vec<String> = keys
                    .iter()
                    .map(|k| {
                        if non_empty(k) {
                            format!("\"{k}\"..#{}#", lua_name(&format!("{name}_{k}")))
                        } else {
                            format!("\"{k}\"")
                        }
                    })
                    .collect();
                parser.push(format!("}},{}", tmp.join(", ")));
            } else {
                let n = keys.len();
                for (i, k) in keys.iter().enumerate() {
                    parser.push(format!(
                        "\"{k}\"..#{}#{}",
                        lua_name(&format!("{name}_{k}")),
                        if i < n - 1 { "," } else { "" }
                    ));
                }
            }
        }
        _ => {}
    }
    parser.push(format!("{})", if printing_args { "" } else { "}" }));
    functions.insert(name.to_string(), Value::from(parser.join("")));
}

/// `autocomplete.getClinkCompletion()`.
pub fn clink(tree: &Obj) -> String {
    let mut functions = Obj::new();
    build_branch(&Value::Object(tree.clone()), &mut functions, "m365");
    let re = regex::Regex::new("#([^#]+)#").unwrap();
    let keys: Vec<String> = functions.keys().cloned().collect();
    for k in keys {
        let text = functions[&k].as_str().unwrap_or("").to_string();
        let replaced = re
            .replace_all(&text, |c: &regex::Captures| {
                functions
                    .get(&c[1])
                    .and_then(Value::as_str)
                    .unwrap_or("")
                    .to_string()
            })
            .into_owned();
        functions.insert(k, Value::from(replaced));
    }
    [
        "local parser = clink.arg.new_parser".to_string(),
        format!(
            "local m365_parser = {}",
            functions.get("m365").and_then(Value::as_str).unwrap_or("")
        ),
        String::new(),
        "clink.arg.register_parser(\"m365\", m365_parser)".into(),
        "clink.arg.register_parser(\"microsoft365\", m365_parser)".into(),
    ]
    .join(m365_core::term::EOL)
}

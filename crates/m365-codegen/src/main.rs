//! Writes `src/generated/manifest.rs` (the static command tables) from a
//! `commands.json` produced by `scripts/extract-upstream.mjs`:
//!
//!     node scripts/extract-upstream.mjs /tmp/cli-microsoft365 > target/commands.json
//!     cargo run -q -p m365-codegen -- target/commands.json [OUT]
//!
//! The output is committed; run this only to pick up a new upstream release
//! and review the diff.

use serde_json::Value;
use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    let mut args = std::env::args().skip(1);
    let input = args
        .next()
        .expect("usage: gen_manifest <commands.json> [out.rs]");
    let out = args.next().map(PathBuf::from).unwrap_or_else(|| {
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../m365-core/src/generated/manifest.rs")
    });
    let text = std::fs::read_to_string(&input).expect("commands.json");
    let manifest: Value = serde_json::from_str(&text).expect("valid manifest");
    std::fs::write(&out, generate(&manifest)).expect("write manifest.rs");
    eprintln!("wrote {}", out.display());
}

/// The Rust source of the command tables.
fn generate(manifest: &Value) -> String {
    let mut code = String::with_capacity(4 << 20);
    code.push_str(
        "// @generated by `cargo run -p m365-codegen`; see crates/m365-codegen/src/main.rs.\n",
    );
    writeln!(
        code,
        "pub const UPSTREAM_VERSION: &str = {};",
        lit(manifest["version"].as_str().unwrap())
    )
    .unwrap();
    writeln!(
        code,
        "pub const UPSTREAM_DESCRIPTION: &str = {};",
        lit(manifest["description"].as_str().unwrap())
    )
    .unwrap();
    code.push_str("pub static COMMANDS: &[CmdMeta] = &[\n");
    let commands = manifest["commands"].as_array().unwrap();
    for c in commands {
        command(&mut code, c);
    }
    code.push_str("];\n");

    // name -> index lookup sorted by name, aliases included
    let mut names: Vec<(String, usize)> = Vec::new();
    for (i, c) in commands.iter().enumerate() {
        names.push((c["name"].as_str().unwrap().to_string(), i));
        for a in c["aliases"].as_array().unwrap() {
            names.push((a.as_str().unwrap().to_string(), i));
        }
    }
    names.sort();
    names.dedup_by(|a, b| a.0 == b.0);
    // upstream's `cli.commands` order (allCommandsFull.json), used by completion
    let mut order: Vec<(u64, usize)> = commands
        .iter()
        .enumerate()
        .map(|(i, c)| (c["order"].as_u64().unwrap_or(i as u64), i))
        .collect();
    order.sort();
    code.push_str("pub static UPSTREAM_ORDER: &[u16] = &[");
    for (_, i) in &order {
        write!(code, "{i},").unwrap();
    }
    code.push_str("];\n");
    code.push_str("pub static NAME_INDEX: &[(&str, u16)] = &[\n");
    for (n, i) in &names {
        writeln!(code, "({}, {i}),", lit(n)).unwrap();
    }
    code.push_str("];\n");
    code
}

fn lit(s: &str) -> String {
    format!("{s:?}")
}

fn opt_lit(v: &Value) -> String {
    match v.as_str() {
        Some(s) => format!("Some({})", lit(s)),
        None => "None".into(),
    }
}

fn str_slice(v: &Value) -> String {
    let mut s = String::from("&[");
    if let Some(a) = v.as_array() {
        for x in a {
            match x {
                Value::String(t) => s.push_str(&lit(t)),
                other => s.push_str(&lit(&other.to_string())),
            }
            s.push(',');
        }
    }
    s.push(']');
    s
}

const BASES: &[&str] = &[
    "AnonymousCommand",
    "SpoCommand",
    "GraphCommand",
    "GraphDelegatedCommand",
    "GraphApplicationCommand",
    "PowerPlatformCommand",
    "PowerAppsCommand",
    "PowerAutomateCommand",
    "PowerBICommand",
    "VivaEngageCommand",
    "PlannerCommand",
    "O365MgmtCommand",
    "AppCommand",
    "ContextCommand",
    "PeriodBasedReport",
    "DateAndPeriodBasedReport",
    "BaseProjectCommand",
    "SpoAppBaseCommand",
    "SpoPropertyBagBaseCommand",
];

fn command(code: &mut String, c: &Value) {
    let mut bases = 0u32;
    for b in c["bases"].as_array().unwrap() {
        if let Some(i) = BASES.iter().position(|x| *x == b.as_str().unwrap()) {
            bases |= 1 << i;
        }
    }
    code.push_str("CmdMeta {");
    write!(code, "name: {},", lit(c["name"].as_str().unwrap())).unwrap();
    write!(code, "aliases: {},", str_slice(&c["aliases"])).unwrap();
    write!(
        code,
        "description: {},",
        lit(c["description"].as_str().unwrap_or(""))
    )
    .unwrap();
    write!(code, "help: {},", lit(c["help"].as_str().unwrap_or(""))).unwrap();
    write!(code, "file: {},", lit(c["file"].as_str().unwrap_or(""))).unwrap();
    write!(code, "bases: {bases},").unwrap();
    code.push_str("options: &[");
    for o in c["options"].as_array().unwrap() {
        let ty = match o["type"].as_str() {
            Some("string") => "OptType::String",
            Some("boolean") => "OptType::Boolean",
            Some("number") => "OptType::Number",
            _ => "OptType::Unknown",
        };
        write!(
            code,
            "OptMeta {{ name: {}, long: {}, short: {}, ty: {ty}, required: {}, autocomplete: {} }},",
            lit(o["name"].as_str().unwrap()),
            opt_lit(&o["long"]),
            opt_lit(&o["short"]),
            o["required"].as_bool().unwrap_or(false),
            str_slice(&o["autocomplete"])
        )
        .unwrap();
    }
    code.push_str("],");
    match c.get("defaultProperties") {
        Some(v) => write!(code, "default_properties: Some({}),", str_slice(v)).unwrap(),
        None => code.push_str("default_properties: None,"),
    }
    write!(
        code,
        "allow_unknown: {},",
        c["allowUnknownOptions"].as_bool().unwrap_or(false)
    )
    .unwrap();
    write!(
        code,
        "custom_action: {},",
        c["customAction"].as_bool().unwrap_or(false)
    )
    .unwrap();
    write!(
        code,
        "allowed_outputs: {},",
        str_slice(&c["allowedOutputs"])
    )
    .unwrap();
    write!(code, "resource: {},", opt_lit(&c["resource"])).unwrap();
    write!(code, "usage_endpoint: {},", opt_lit(&c["usageEndpoint"])).unwrap();
    write!(code, "url_options: {},", str_slice(&c["urlOptions"])).unwrap();
    write!(code, "strict: {},", c["strict"].as_bool().unwrap_or(false)).unwrap();
    write!(code, "loose: {},", c["loose"].as_bool().unwrap_or(false)).unwrap();
    let errs = match c["errors"].as_str() {
        Some("json") => "ErrStyle::Json",
        Some("viva") => "ErrStyle::Viva",
        Some("odata") => "ErrStyle::OData",
        Some("plain") => "ErrStyle::Plain",
        _ => "ErrStyle::None",
    };
    write!(code, "errors: {errs},").unwrap();
    code.push_str("fields: &[");
    let mut custom_idx = 0u16;
    if let Some(fields) = c["fields"].as_object() {
        for (name, f) in fields {
            field(code, name, f, &mut custom_idx);
        }
    }
    code.push_str("],");
    code.push_str("refines: &[");
    let refines = c
        .get("refines")
        .and_then(|r| r.as_array())
        .cloned()
        .or_else(|| c.get("schemaChecks").and_then(|r| r.as_array()).cloned())
        .unwrap_or_default();
    for r in refines.iter() {
        refine(code, r);
    }
    code.push_str("],");
    if c["legacy"].as_bool().unwrap_or(false) {
        code.push_str("legacy: Some(Legacy {");
        write!(
            code,
            "custom_validators: {},",
            c["customValidators"].as_u64().unwrap_or(0)
        )
        .unwrap();
        write!(code, "strings: {},", str_slice(&c["types"]["string"])).unwrap();
        write!(code, "booleans: {},", str_slice(&c["types"]["boolean"])).unwrap();
        code.push_str("option_sets: &[");
        for s in c["optionSets"].as_array().unwrap() {
            write!(
                code,
                "OptionSet {{ options: {}, runs_when: {} }},",
                str_slice(&s["options"]),
                opt_lit(&s["runsWhen"])
            )
            .unwrap();
        }
        code.push_str("]}),");
    } else {
        code.push_str("legacy: None,");
    }
    code.push_str("},\n");
}

fn ftype(t: Option<&str>) -> &'static str {
    match t {
        Some("string") => "FType::String",
        Some("boolean") => "FType::Boolean",
        Some("number") => "FType::Number",
        Some("enum") => "FType::Enum",
        Some("array") => "FType::Array",
        Some("union") => "FType::Union",
        _ => "FType::Other",
    }
}

fn msg(v: &Value) -> String {
    match v.as_str() {
        Some("<dynamic>") => "Msg::Dynamic".into(),
        Some(s) => format!("Msg::Text({})", lit(s)),
        None => "Msg::Default".into(),
    }
}

